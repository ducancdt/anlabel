    /// <summary>
    /// Resolves the GS1 AI for a stored identifier id and multiplier; false
    /// for an id the vendor table does not define.
    /// </summary>
    public static bool TryGetApplicationIdentifier(int id, int multiplier, out string applicationIdentifier, out bool carriesCheckDigit)
    {
        applicationIdentifier = string.Empty;
        carriesCheckDigit = false;
        if (!Table.TryGetValue(id, out var row))
        {
            return false;
        }

        carriesCheckDigit = (row.Attributes & CheckDigitFlag) != 0;
        applicationIdentifier = (row.Attributes & MultiplierFlag) != 0
            ? row.Code + Math.Clamp(multiplier, 0, 9).ToString(System.Globalization.CultureInfo.InvariantCulture)
            : row.Code;
        return true;
    }

    /// <summary>
    /// Digits of a check-digit AI's value, check digit included (GS1 General
    /// Specifications); null for an AI whose length is not fixed here.
    /// </summary>
    public static int? DigitsWithCheckDigit(string applicationIdentifier) => applicationIdentifier switch
    {
        "00" or "8017" or "8018" => 18,
        "01" or "02" => 14,
        "402" => 17,
        "410" or "411" or "412" or "413" or "414" or "415" or "416" or "417" => 13,
        _ => null
    };

    /// <summary>True for the GS1 date AIs whose value is a yyMMdd date.</summary>
    public static bool IsDateApplicationIdentifier(string applicationIdentifier) =>
        applicationIdentifier is "11" or "12" or "13" or "15" or "16" or "17";
